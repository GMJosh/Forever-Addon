"""Fetch quest and dungeon data from the ForeverDB API into LevelPace/Data/Quests.lua and Dungeons.lua.

Run:  python tools/fetch_advisor.py     (about 3 minutes)
The API key is read from the FOREVERDB_KEY environment variable and is never written to a file.
Data from ForeverDB.net (https://foreverdb.net); LevelPace shows their credit in the Advisor tab.
"""
import json, os, sys, time, urllib.request, urllib.error
from pathlib import Path

BASE = "https://api.foreverdb.net/api/v1"
OUT = Path(__file__).resolve().parent.parent / "LevelPace" / "Data"
PAUSE = 2.2

key = os.environ.get("FOREVERDB_KEY")
if not key:
    sys.exit("Set the FOREVERDB_KEY environment variable first.")


def get(path):
    req = urllib.request.Request(BASE + path, headers={"X-API-Key": key, "User-Agent": "ForeverAddonTools/1.0"})
    for attempt in range(8):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.load(resp)
            time.sleep(PAUSE)
            return data
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                time.sleep(20 if e.code == 429 else 10 * (attempt + 1))
                continue
            raise
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            time.sleep(10 * (attempt + 1))
    raise RuntimeError("gave up after retries: " + path)


def s(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    only_dungeons = "dungeons" in sys.argv[1:]
    # ---- quests
    quests, offset, build = [], 0, ""
    while not only_dungeons:
        page = get(f"/quests?limit=100&offset={offset}")
        quests.extend(page["data"])
        build = page["meta"].get("build", build)
        if offset + page["meta"]["limit"] >= page["meta"]["total"]:
            break
        offset += page["meta"]["limit"]
        if (offset // 100) % 10 == 0:
            print(f"  {offset}/{page['meta']['total']} quests")
    zones = {}
    rows = []
    known = 0
    for q in ([] if only_dungeons else quests):
        z = q.get("zone") or {}
        if not z.get("m") or q.get("level") is None:
            continue
        zones[z["m"]] = z.get("n") or str(z["m"])
        side = {"a": "A", "h": "H"}.get(str(q.get("side") or "").lower()[:1], "B")
        k = 1 if q.get("knownInForever") else 0
        known += k
        parts = [f"id={q['id']}", f"n={s(q['name'])}", f"l={q['level']}", f"r={q.get('requiredLevel') or 0}", f"s={s(side)}", f"m={z['m']}", f"k={k}"]
        st = q.get("starts") or {}
        loc = st.get("location") or {}
        if st.get("type") == "npc" and st.get("name") and loc.get("uiMapId") and loc.get("x") is not None:
            parts += [f"sn={s(st['name'])}", f"sm={loc['uiMapId']}", f"sx={loc['x']:.1f}", f"sy={loc['y']:.1f}"]
        rows.append("\t{" + ", ".join(parts) + "},")
    out = ["-- Generated by tools/fetch_advisor.py. Do not edit by hand.", "-- Data from ForeverDB.net (https://foreverdb.net).",
           "-- id quest, n name, l level, r required level, s side A/H/B, m zone map id, k known in Forever, sn/sm/sx/sy where it starts.",
           "local addonName, ns = ...", "ns.QuestData = {", "zones = {"]
    out += [f"\t[{m}] = {s(n)}," for m, n in sorted(zones.items())]
    out += ["},", "list = {"] + rows + ["},", "}", f"ns.QuestBuild = {s(build)}"]
    if not only_dungeons:
        (OUT / "Quests.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
        print(f"Quests: {len(rows)} written ({known} known in Forever), {len(zones)} zones")

    # ---- dungeons and raids
    lst = get("/dungeons")["data"]
    rows = []
    statuses = {}
    for d in lst:
        rng = d.get("levelRange")
        if not rng:
            continue
        statuses[d.get("status")] = statuses.get(d.get("status"), 0) + 1
        detail = get(f"/dungeons/{d['id']}")["data"]
        bosses = [b if isinstance(b, str) else b.get("name") for b in (detail.get("bosses") or []) if isinstance(b, str) or (isinstance(b, dict) and b.get("name"))]
        rows.append("\t{id=%d, n=%s, kind=%s, p=%d, lo=%d, hi=%d, st=%s, new=%s, bosses={%s}}," % (
            d["id"], s(d["name"]), s(d.get("kind") or ""), d.get("players") or 0, rng[0], rng[1], s(d.get("status") or ""),
            "true" if d.get("newInForever") else "false", ", ".join(s(b) for b in bosses)))
    out = ["-- Generated by tools/fetch_advisor.py. Do not edit by hand.", "-- Data from ForeverDB.net (https://foreverdb.net).",
           "-- n name, kind dungeon/raid, p players, lo/hi level range, st status (classic/other/...), new = new in Forever.",
           "local addonName, ns = ...", "ns.DungeonData = {"] + rows + ["}"]
    (OUT / "Dungeons.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Dungeons: {len(rows)} written; statuses {statuses}")


main()
