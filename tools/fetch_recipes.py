"""Fetch crafting recipe data from the ForeverDB API into CraftPath/Data/Recipes.lua.

Run from anywhere:  python tools/fetch_recipes.py
The API key is read from the FOREVERDB_KEY environment variable. It is never written to a file.
Data from ForeverDB.net (https://foreverdb.net). Keep the credit link wherever the data is shown.
"""
import json, os, sys, time, urllib.request, urllib.error
from pathlib import Path

BASE = "https://api.foreverdb.net/api/v1"
PROFESSIONS = ["alchemy", "blacksmithing", "enchanting", "engineering", "leatherworking",
               "tailoring", "cooking", "first-aid", "mining"]
OUT = Path(__file__).resolve().parent.parent / "CraftPath" / "Data" / "Recipes.lua"
PAUSE = 2.2  # the free tier allows 30 requests a minute

key = os.environ.get("FOREVERDB_KEY")
if not key:
    sys.exit("Set the FOREVERDB_KEY environment variable first.")


def get(path):
    req = urllib.request.Request(BASE + path, headers={"X-API-Key": key, "User-Agent": "ForeverAddonTools/1.0"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                return json.load(resp)
        except urllib.error.HTTPError as e:
            if e.code == 429:
                time.sleep(15)
                continue
            raise
    raise RuntimeError("rate limited: " + path)


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def recipe_line(r):
    sk = r.get("skill") or {}
    if sk.get("orange") is None or sk.get("grey") is None:
        return None
    reagents = r.get("reagents") or []
    if not reagents:
        return None
    ways = ((r.get("learnedFrom") or {}).get("sources") or {}).get("ways") or []
    learn_at = ((r.get("learnedFrom") or {}).get("sources") or {}).get("learnAtSkill")
    auto = (r.get("learnedFrom") or {}).get("automatic")
    if auto:
        ways = ["auto"]
    makes = r.get("makes") or {}
    parts = [
        f"id={r['spellId']}", f"n={lua_str(r['name'])}",
        f"o={sk['orange']}", f"y={sk.get('yellow', sk['orange'])}", f"g={sk.get('green', sk['grey'])}", f"x={sk['grey']}",
        "r={" + ",".join("{%d,%d}" % (g["itemId"], g["count"]) for g in reagents if g.get("itemId")) + "}",
    ]
    if makes.get("itemId"):
        parts.append(f"out={makes['itemId']}")
        parts.append(f"q={makes.get('count', 1)}")
    if ways:
        parts.append("w=" + lua_str(",".join(ways)))
    if learn_at is not None:
        parts.append(f"ls={learn_at}")
    return "\t\t{" + ", ".join(parts) + "},"


def main():
    meta_build = None
    lines = ["-- Generated by tools/fetch_recipes.py. Do not edit by hand.",
             "-- Data from ForeverDB.net (https://foreverdb.net).",
             "-- Recipe fields: id spell, n name, o/y/g/x skill where orange/yellow/green/grey start,",
             "-- r reagents {itemID, count}, out/q output item and count, w how it is learned, ls skill it is learned at.",
             "local addonName, ns = ...", "ns.RecipeData = {"]
    total = 0
    for slug in PROFESSIONS:
        recipes, offset, name = [], 0, None
        while True:
            data = get(f"/professions/{slug}?limit=100&offset={offset}")
            time.sleep(PAUSE)
            name = data["data"]["name"]
            meta_build = data["meta"].get("build")
            recipes.extend(data["data"]["recipes"])
            if offset + data["meta"]["limit"] >= data["meta"]["total"]:
                break
            offset += data["meta"]["limit"]
        ranks = {r["rank"]: r["maxSkill"] for r in data["data"].get("ranks", [])}
        rows = [l for l in (recipe_line(r) for r in recipes) if l]
        total += len(rows)
        print(f"{name}: {len(rows)} recipes with thresholds and reagents (of {len(recipes)})")
        lines.append(f"\t[{lua_str(name)}] = {{ max = {max(ranks.values()) if ranks else 0}, recipes = {{")
        lines.extend(rows)
        lines.append("\t} },")
    lines.append("}")
    lines.append(f"ns.RecipeBuild = {lua_str(meta_build or '')}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({total} recipes, build {meta_build})")


main()
