"""Fetch vendor prices and gathering spots from the ForeverDB API into CraftPath/Data/Vendors.lua and Gathering.lua.

Run (takes about 40 minutes, it makes ~1,100 requests at the free-tier pace):  python tools/fetch_world.py
The API key is read from the FOREVERDB_KEY environment variable and is never written to a file.
Only reagents used by CraftPath's recipes are kept. Data from ForeverDB.net (https://foreverdb.net).
"""
import json, os, re, sys, time, urllib.request, urllib.error
from pathlib import Path

BASE = "https://api.foreverdb.net/api/v1"
ROOT = Path(__file__).resolve().parent.parent
RECIPES = ROOT / "CraftPath" / "Data" / "Recipes.lua"
CACHE = ROOT / "tools" / ".cache"
PAUSE = 2.2

key = os.environ.get("FOREVERDB_KEY")
if not key:
    sys.exit("Set the FOREVERDB_KEY environment variable first.")


def get(path):
    req = urllib.request.Request(BASE + path, headers={"X-API-Key": key, "User-Agent": "ForeverAddonTools/1.0"})
    for attempt in range(8):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.load(resp)
            time.sleep(PAUSE)
            return data
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:  # rate limit or a temporary server problem: wait and try again
                time.sleep(20 if e.code == 429 else 10 * (attempt + 1))
                continue
            raise
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            time.sleep(10 * (attempt + 1))
    raise RuntimeError("gave up after retries: " + path)


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def reagent_ids():
    text = RECIPES.read_text(encoding="utf-8")
    ids = set()
    for block in re.findall(r"r=(\{.*?\}\}),", text):
        ids.update(int(i) for i in re.findall(r"\{(\d+),\d+\}", block))
    return ids


def side_code(side):
    s = (side or "").lower()
    return "A" if s.startswith("all") else "H" if s.startswith("hor") else "N"


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    wanted = reagent_ids()
    print(f"{len(wanted)} reagent items to look for")

    # ---- gathering (herbs and ore)
    gather = {}
    for slug in ("herbalism", "mining"):
        body = get(f"/gathering/{slug}")["data"]
        for node in body.get("nodes", []):
            item = (node.get("item") or {}).get("itemId")
            targets = [item] + [g.get("itemId") for g in node.get("alsoGives", []) if isinstance(g, dict)]
            zones = [z["name"] for z in (node.get("topZones") or [])[:3]]
            for t in targets:
                if t in wanted and t not in gather:
                    gather[t] = {"k": slug, "skill": node.get("skill") or 0, "z": zones}
        print(f"{slug}: {len(gather)} reagents so far")
    out = ["-- Generated by tools/fetch_world.py. Do not edit by hand.", "-- Data from ForeverDB.net (https://foreverdb.net).",
           "-- [itemID] = { k = kind, skill = needed skill, z = best zones }", "local addonName, ns = ...", "ns.GatherData = {"]
    for item in sorted(gather):
        g = gather[item]
        out.append(f"\t[{item}] = {{ k={lua_str(g['k'])}, skill={g['skill']}, z={{{', '.join(lua_str(z) for z in g['z'])}}} }},")
    out.append("}")
    (ROOT / "CraftPath" / "Data" / "Gathering.lua").write_text("\n".join(out) + "\n", encoding="utf-8")

    # ---- vendors: list them all, then read what each sells (cached so a stop can resume)
    vendors, offset = [], 0
    while True:
        page = get(f"/vendors?limit=100&offset={offset}")
        vendors.extend(page["data"])
        if offset + page["meta"]["limit"] >= page["meta"]["total"]:
            break
        offset += page["meta"]["limit"]
    print(f"{len(vendors)} vendors")
    cache_file = CACHE / "vendors.json"
    cache = json.loads(cache_file.read_text()) if cache_file.exists() else {}
    best = {}  # item -> { side code -> entry }
    for n, v in enumerate(vendors, 1):
        vid = str(v["id"])
        if vid not in cache:
            one = get(f"/vendors/{vid}")["data"]
            cache[vid] = {"sells": [s for s in one.get("sells", []) if s["itemId"] in wanted], "v": v}
            if n % 25 == 0:
                cache_file.write_text(json.dumps(cache))
                print(f"  {n}/{len(vendors)} vendors read")
        for s in cache[vid]["sells"]:
            costs = s.get("costs")
            if s.get("pricePerItem") is None or costs:  # skip entries that also cost another currency or item
                continue
            code = side_code(v.get("side"))
            entry = {"p": round(s["pricePerItem"]), "n": v["name"], "z": v.get("zone") or "", "m": v.get("mapId") or 0,
                     "x": v.get("x") or 0, "y": v.get("y") or 0, "s": code, "l": bool(s.get("limited"))}
            cur = best.setdefault(s["itemId"], {}).get(code)
            # prefer unlimited stock, then the lower price
            if cur is None or (entry["l"], entry["p"]) < (cur["l"], cur["p"]):
                best[s["itemId"]][code] = entry
    cache_file.write_text(json.dumps(cache))
    out = ["-- Generated by tools/fetch_world.py. Do not edit by hand.", "-- Data from ForeverDB.net (https://foreverdb.net).",
           "-- [itemID] = list of { p price per item in copper, n vendor, z zone, m map id, x/y coords, s side A/H/N, l limited stock }",
           "local addonName, ns = ...", "ns.VendorData = {"]
    for item in sorted(best):
        rows = ", ".join("{p=%d, n=%s, z=%s, m=%d, x=%.1f, y=%.1f, s=%s, l=%s}" % (e["p"], lua_str(e["n"]), lua_str(e["z"]), e["m"], e["x"], e["y"], lua_str(e["s"]), "true" if e["l"] else "false")
                         for e in best[item].values())
        out.append(f"\t[{item}] = {{ {rows} }},")
    out.append("}")
    (ROOT / "CraftPath" / "Data" / "Vendors.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Vendor prices for {len(best)} of {len(wanted)} reagents; gathering spots for {len(gather)}")


main()
